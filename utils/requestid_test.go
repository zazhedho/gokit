package utils

import (
	"context"
	"net/http/httptest"
	"testing"

	"github.com/gin-gonic/gin"
	"github.com/google/uuid"
	"github.com/zazhedho/logus"
)

func TestRequestIDIsSharedWithLogus(t *testing.T) {
	id := uuid.New()

	// utils -> logus
	if got := logus.RequestID(WithRequestID(context.Background(), id)); got != id {
		t.Fatalf("logus did not read utils request id: got %s want %s", got, id)
	}

	// logus -> utils
	if got := GenerateLogId(logus.WithRequestID(context.Background(), id)); got != id {
		t.Fatalf("GenerateLogId did not read logus request id: got %s want %s", got, id)
	}
	if got := GetRequestID(logus.WithRequestID(context.Background(), id)); got != id.String() {
		t.Fatalf("GetRequestID did not read logus request id: got %q want %q", got, id.String())
	}

	// gin context: id generated by GenerateLogId is readable by logus
	gin.SetMode(gin.TestMode)
	c, _ := gin.CreateTestContext(httptest.NewRecorder())
	generated := GenerateLogId(c)
	if logus.RequestID(c) != generated {
		t.Fatalf("logus did not read id generated by GenerateLogId: got %s want %s", logus.RequestID(c), generated)
	}
	if CtxKeyId != logus.CtxKeyID {
		t.Fatalf("CtxKeyId %q != logus.CtxKeyID %q", CtxKeyId, logus.CtxKeyID)
	}
}
